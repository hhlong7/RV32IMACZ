#!/usr/bin/env python3
"""Generate test_files/lockstep/fp_arith.s: a table-driven FP lockstep test.

Every operand pair runs fadd/fsub/fmul/fdiv.s in all five static rounding
modes plus the dynamic mode (frm cycles through 0-4 per pair). fflags is read
and cleared after each operation, so Spike checks every result and every
flag set. Results are also stored, so the memory-write trace checks fsw.

  python3 tools/gen_fp_lockstep.py
"""

from __future__ import annotations

import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import fp_ref  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "test_files" / "lockstep" / "fp_arith.s"
PAIRS = 300
SEED = 2026


def operand_pairs() -> list[tuple[int, int]]:
    rng = random.Random(SEED)
    specials = fp_ref.SPECIALS
    pairs = [(a, b) for a in specials[::2] for b in specials[1::2]]   # specials x specials
    while len(pairs) < PAIRS:
        a = fp_ref.random_operand(rng)
        b = fp_ref.related_operand(rng, a) if rng.random() < 0.4 else fp_ref.random_operand(rng)
        pairs.append((a, b))
    return pairs[:PAIRS]


def main() -> int:
    pairs = operand_pairs()
    table = "\n".join(f"    .word 0x{a:08x}, 0x{b:08x}" for a, b in pairs)
    OUT.write_text(f"""# FP arithmetic against Spike: {PAIRS} operand pairs (specials x specials,
# random, near-cancelling) through fadd/fsub/fmul/fdiv.s in every rounding
# mode, reading and clearing fflags after each operation.
# Generated by tools/gen_fp_lockstep.py; edit the generator, not this file.
.include "harness.inc"

.macro FP_OPS rm
    fadd.s f3, f1, f2, \\rm
    csrrw a0, fflags, x0
    fsub.s f4, f1, f2, \\rm
    csrrw a1, fflags, x0
    fmul.s f5, f1, f2, \\rm
    csrrw a2, fflags, x0
    fdiv.s f6, f1, f2, \\rm
    csrrw a3, fflags, x0
.endm

LOCKSTEP_START
FP_INIT
    la s0, fp_operands
    li s1, {PAIRS}
    la s2, fp_results
1:  flw f1, 0(s0)
    flw f2, 4(s0)
    # Dynamic rounding mode cycles through 0-4.
    li t1, 5
    remu t1, s1, t1
    csrw frm, t1
    .irp rm, rne, rtz, rdn, rup, rmm, dyn
    FP_OPS \\rm
    .endr
    # Results feed straight back in (FP forwarding) and get stored.
    fadd.s f7, f3, f4
    fmul.s f8, f7, f5
    fsw f8, 0(s2)
    fsw f6, 4(s2)
    csrr a4, fcsr
    csrw fflags, x0
    addi s0, s0, 8
    addi s2, s2, 8
    addi s1, s1, -1
    bnez s1, 1b
    csrr a5, mstatus
LOCKSTEP_PASS
LOCKSTEP_FOOTER

    .data
    .balign 8
fp_operands:
{table}
fp_results:
    .fill {2 * PAIRS}, 4, 0
""")
    print(f"wrote {OUT.relative_to(ROOT)} ({PAIRS} pairs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
